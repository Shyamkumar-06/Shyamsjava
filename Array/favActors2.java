class favActors2
{
	public static void main(String[] args)
	{
		char arr[][]={{'A','j','i','t','h'},{'K','u','m','a','r'},{'S','h','y','a','m'},{'K','u','m','a','r'}};
		for(int i=0;i<=arr.length;i++)
		{
			for(int j=0;j<arr[i].length;j++)
			{
				System.out.print(arr[i][j]+" ");
			}
			System.out.println(" ");
		}
	}
}